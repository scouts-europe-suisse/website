/** Le SVG autonome d'un pictogramme, tel qu'il est servi en fichier. */
export function pictoSvg(key: PictoKey): string {
  const p = PICTOS[key];
  const transform = p.transform ? ` transform="${p.transform}"` : '';
  const rule = p.fillRule ? ` fill-rule="${p.fillRule}"` : '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="${p.label.fr}">` +
    `<circle cx="32" cy="32" r="32" fill="${BRANCHE_HEX[p.branche]}"/>` +
    `<path d="${p.path}"${transform} fill="#fff"${rule}/>` +
    `</svg>\n`
  );
}
